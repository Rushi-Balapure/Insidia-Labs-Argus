"""Regenerate hash-pinned engine locks.

From core/:

    uv run python scripts/lock_engines.py

Python engines resolve for 3.12, the interpreter `engines install` puts in the
venv, with `--universal` so each pin carries a hash for every platform wheel.
Garak uses the CPU torch backend. SkillSpector is the commit for tag v2.12.0,
not the tag. promptfoo is an npm lock installed later with `npm ci`.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCKS = ROOT / "insidia" / "locks"
SKILLSPECTOR_COMMIT = "c7958a3268d9498644b22edb75d0f051bbc8cbfc"  # tag v2.12.0

PIP: dict[str, str] = {
    "bandit": "bandit==1.9.4\n",
    "deepteam": "deepteam==1.0.9\nsentry-sdk==2.71.0\n",
    "pyrit": "pyrit==1.1.0\n",
    "nuguard": "nuguard==0.9.15\ncryptography==50.0.2\n",
    "mcp-scanner": "cisco-ai-mcp-scanner==4.8.5\n",
    "garak": "garak==0.17.0\ntorch\n",
    "skillspector": (
        "skillspector @ https://github.com/NVIDIA/SkillSpector/archive/"
        f"{SKILLSPECTOR_COMMIT}.tar.gz\n"
    ),
}
PIP_ARGS: dict[str, list[str]] = {"garak": ["--torch-backend", "cpu"]}
HEADER = "# Generated by scripts/lock_engines.py. Do not edit.\n"


def _compile(name: str, requirements: str) -> None:
    source = LOCKS / f".{name}.in"
    destination = LOCKS / f"{name}.txt"
    source.write_text(requirements, encoding="utf-8")
    command = [
        "uv",
        "pip",
        "compile",
        str(source),
        "--generate-hashes",
        "--universal",
        "--python-version",
        "3.12",
        "--no-header",
        "--no-annotate",
        "-o",
        str(destination),
        *PIP_ARGS.get(name, []),
    ]
    try:
        subprocess.run(command, check=True)
    finally:
        source.unlink(missing_ok=True)
    body = destination.read_text(encoding="utf-8")
    if "git+" in body:
        raise SystemExit(f"{name} lock still contains a git ref")
    destination.write_text(HEADER + body, encoding="utf-8")


def _promptfoo() -> None:
    dest = LOCKS / "promptfoo"
    dest.mkdir(parents=True)
    manifest = dest / "package.json"
    manifest.write_text(
        "{\n"
        '  "name": "insidia-promptfoo",\n'
        '  "private": true,\n'
        '  "dependencies": {\n'
        '    "promptfoo": "0.124.0"\n'
        "  }\n"
        "}\n",
        encoding="utf-8",
    )
    subprocess.run(
        ["npm", "install", "--package-lock-only", "--ignore-scripts", "--silent"],
        cwd=dest,
        check=True,
    )


def main() -> None:
    LOCKS.mkdir(parents=True, exist_ok=True)
    for name, requirements in PIP.items():
        _compile(name, requirements)
    _promptfoo()
    from insidia.engines import _require_lock_hashes, _require_npm_integrity

    for name in PIP:
        _require_lock_hashes(LOCKS / f"{name}.txt")
    _require_npm_integrity(LOCKS / "promptfoo" / "package-lock.json")


if __name__ == "__main__":
    main()
